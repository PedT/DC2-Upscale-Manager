"""Regenerate core/data/room_keys.json from the room research outputs.

The GOG wrapper keys a room background by the CRC32 of the game's own (x87 float-IDCT) JPEG decode,
which is slow to reproduce in Python. The research run already predicted those keys for every camera,
so this script freezes them into a lookup table indexed by the CRC32 of the JPEG payload. Identical
JPEGs decode identically, so the table works for any install that ships the same room data.

Keys are PREDICTED (decoder model, never confirmed in game). Two FPU-precision variants exist:
  pc53 = primary guess, pc24 = alternative. Both are stored.

Usage: python -I tools/build_room_keys.py [--work C:/Claude/DinoCrisis2ModWork/work/wf/rooms]
"""
import argparse
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "core", "data", "room_keys.json")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default="C:/Claude/DinoCrisis2ModWork/work/wf/rooms")
    a = ap.parse_args()
    pred = json.load(open(os.path.join(a.work, "predicted_wrapper_crcs.json"), encoding="utf-8"))
    table = {}
    conflicts = 0
    with open(os.path.join(a.work, "rooms_inventory.csv"), newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            jcrc = row["jpg_crc32"].upper()
            p = pred[f"{row['file']}:{row['cam']}"]
            keys = {"key32": p["crc32_pc53"], "key16": p["crc16_pc53"],
                    "key32_alt": p["crc32_pc24"], "key16_alt": p["crc16_pc24"]}
            if jcrc in table and table[jcrc] != keys:
                conflicts += 1
            table[jcrc] = keys
    if conflicts:
        raise SystemExit(f"{conflicts} JPEG CRCs map to different keys - refusing to write")
    payload = {"_about": "jpeg payload crc32 -> predicted GOG-wrapper keys (pc53 primary, pc24 alt). "
                         "Generated by tools/build_room_keys.py; unverified in game.",
               "keys": dict(sorted(table.items()))}
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=0)
    print(f"wrote {len(table)} entries -> {os.path.abspath(OUT)}")


if __name__ == "__main__":
    main()
